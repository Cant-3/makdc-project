const express = require('express');
const router = express.Router();
const contentController = require('../controllers/content.controller');
const { authenticate, requireSuperAdmin } = require('../middleware/auth');
const {updateContentSchema,validate} = require('../validators/content.validator');
router.get('/', contentController.listContent);
router.post('/', authenticate, requireSuperAdmin, contentController.createOrUpdateContent);
router.get('/:key', contentController.getContent);
router.put('/:key', authenticate, requireSuperAdmin, validate(updateContentSchema),contentController.updateContent);
module.exports = router;